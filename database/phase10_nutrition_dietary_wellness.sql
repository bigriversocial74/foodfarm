    CONSTRAINT fk_nutrition_recommendation_actor FOREIGN KEY (acted_by_member_id) REFERENCES household_members(id) ON DELETE SET NULL,
    UNIQUE KEY uq_nutrition_recommendation_generation (household_id, generation_key),
    INDEX idx_nutrition_recommendation_status (household_id, status, priority, due_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

