CREATE TABLE IF NOT EXISTS household_nutrition_settings (
    household_id BIGINT UNSIGNED PRIMARY KEY,
    assessment_window_days SMALLINT UNSIGNED NOT NULL DEFAULT 7,
    minimum_recipe_variety SMALLINT UNSIGNED NOT NULL DEFAULT 5,
    minimum_data_completeness_percent DECIMAL(5,2) NOT NULL DEFAULT 80.00,
    show_optional_targets TINYINT(1) NOT NULL DEFAULT 1,
    updated_by_member_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_nutrition_settings_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_nutrition_settings_member FOREIGN KEY (updated_by_member_id) REFERENCES household_members(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

