SET NAMES utf8mb4;
SET time_zone = '+00:00';

CREATE TABLE IF NOT EXISTS household_finance_settings (
    household_id BIGINT UNSIGNED PRIMARY KEY,
    monthly_budget DECIMAL(12,2) NOT NULL DEFAULT 600.00,
    waste_target_percent DECIMAL(5,2) NOT NULL DEFAULT 5.00,
    savings_target_amount DECIMAL(12,2) NOT NULL DEFAULT 100.00,
    price_increase_alert_percent DECIMAL(5,2) NOT NULL DEFAULT 15.00,
    updated_by_member_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_finance_settings_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_finance_settings_member FOREIGN KEY (updated_by_member_id) REFERENCES household_members(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS household_suppliers (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    household_id BIGINT UNSIGNED NOT NULL,
    name VARCHAR(180) NOT NULL,
    supplier_type ENUM('grocery','farm','warehouse','market','online','restaurant_supply','other') NOT NULL DEFAULT 'grocery',
    status ENUM('active','inactive') NOT NULL DEFAULT 'active',
    notes TEXT NULL,
    created_by_member_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_household_suppliers_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_household_suppliers_member FOREIGN KEY (created_by_member_id) REFERENCES household_members(id) ON DELETE SET NULL,
    UNIQUE KEY uq_household_supplier_name (household_id, name),
    INDEX idx_household_suppliers_status (household_id, status, name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS food_purchase_records (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    household_id BIGINT UNSIGNED NOT NULL,
    inventory_item_id BIGINT UNSIGNED NOT NULL,
    supplier_id BIGINT UNSIGNED NULL,
    purchased_by_member_id BIGINT UNSIGNED NULL,
    action_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    purchased_on DATE NOT NULL,
    quantity DECIMAL(14,4) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    package_quantity DECIMAL(14,4) NULL,
    package_unit VARCHAR(30) NULL,
    total_cost DECIMAL(12,2) NOT NULL,
    unit_cost DECIMAL(14,6) NOT NULL,
    receipt_reference VARCHAR(190) NULL,
    notes TEXT NULL,
    ledger_event_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_purchase_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_purchase_item FOREIGN KEY (inventory_item_id) REFERENCES inventory_items(id) ON DELETE RESTRICT,
    CONSTRAINT fk_purchase_supplier FOREIGN KEY (supplier_id) REFERENCES household_suppliers(id) ON DELETE SET NULL,
    CONSTRAINT fk_purchase_member FOREIGN KEY (purchased_by_member_id) REFERENCES household_members(id) ON DELETE SET NULL,
    CONSTRAINT fk_purchase_ledger FOREIGN KEY (ledger_event_id) REFERENCES food_ledger_events(id) ON DELETE SET NULL,
    UNIQUE KEY uq_purchase_household_action (household_id, action_key),
    INDEX idx_purchase_household_date (household_id, purchased_on, id),
    INDEX idx_purchase_item_date (household_id, inventory_item_id, purchased_on, id),
    INDEX idx_purchase_supplier_item (household_id, supplier_id, inventory_item_id, purchased_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS inventory_cost_basis (
    household_id BIGINT UNSIGNED NOT NULL,
    inventory_item_id BIGINT UNSIGNED NOT NULL,
    unit VARCHAR(30) NOT NULL,
    weighted_unit_cost DECIMAL(14,6) NOT NULL,
    quantity_costed DECIMAL(14,4) NOT NULL,
    source_purchase_id BIGINT UNSIGNED NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (household_id, inventory_item_id),
    CONSTRAINT fk_cost_basis_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_cost_basis_item FOREIGN KEY (inventory_item_id) REFERENCES inventory_items(id) ON DELETE CASCADE,
    CONSTRAINT fk_cost_basis_purchase FOREIGN KEY (source_purchase_id) REFERENCES food_purchase_records(id) ON DELETE SET NULL,
    INDEX idx_cost_basis_updated (household_id, updated_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS food_waste_events (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    household_id BIGINT UNSIGNED NOT NULL,
    inventory_item_id BIGINT UNSIGNED NULL,
    prepared_food_batch_id BIGINT UNSIGNED NULL,
    member_id BIGINT UNSIGNED NULL,
    action_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    waste_type ENUM('spoiled','composted','discarded','overproduction','trim_loss','expired','damaged','other') NOT NULL,
    quantity DECIMAL(14,4) NOT NULL,
    unit VARCHAR(30) NOT NULL,
    estimated_value DECIMAL(12,2) NOT NULL DEFAULT 0,
    reason VARCHAR(500) NULL,
    occurred_on DATE NOT NULL,
    ledger_event_id BIGINT UNSIGNED NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_waste_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_waste_item FOREIGN KEY (inventory_item_id) REFERENCES inventory_items(id) ON DELETE SET NULL,
    CONSTRAINT fk_waste_prepared FOREIGN KEY (prepared_food_batch_id) REFERENCES prepared_food_batches(id) ON DELETE SET NULL,
    CONSTRAINT fk_waste_member FOREIGN KEY (member_id) REFERENCES household_members(id) ON DELETE SET NULL,
    CONSTRAINT fk_waste_ledger FOREIGN KEY (ledger_event_id) REFERENCES food_ledger_events(id) ON DELETE SET NULL,
    UNIQUE KEY uq_waste_household_action (household_id, action_key),
    INDEX idx_waste_household_date (household_id, occurred_on, id),
    INDEX idx_waste_item_date (household_id, inventory_item_id, occurred_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS recipe_cost_snapshots (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
