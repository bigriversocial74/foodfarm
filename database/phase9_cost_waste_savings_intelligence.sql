CREATE TABLE IF NOT EXISTS household_finance_snapshots (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    household_id BIGINT UNSIGNED NOT NULL,
    month_start DATE NOT NULL,
    month_end DATE NOT NULL,
    run_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    source_watermark CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    model_version VARCHAR(40) NOT NULL DEFAULT 'deterministic-v1',
    status ENUM('running','completed','failed') NOT NULL DEFAULT 'running',
    budget_amount DECIMAL(12,2) NOT NULL DEFAULT 0,
    purchase_spend DECIMAL(12,2) NOT NULL DEFAULT 0,
    waste_value DECIMAL(12,2) NOT NULL DEFAULT 0,
    household_production_value DECIMAL(12,2) NOT NULL DEFAULT 0,
    preservation_value DECIMAL(12,2) NOT NULL DEFAULT 0,
    estimated_savings DECIMAL(12,2) NOT NULL DEFAULT 0,
    budget_variance DECIMAL(12,2) NOT NULL DEFAULT 0,
    waste_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
    savings_rate_percent DECIMAL(5,2) NOT NULL DEFAULT 0,
    purchase_count INT UNSIGNED NOT NULL DEFAULT 0,
    waste_event_count INT UNSIGNED NOT NULL DEFAULT 0,
    recommendation_count INT UNSIGNED NOT NULL DEFAULT 0,
    generated_by_member_id BIGINT UNSIGNED NOT NULL,
    started_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at DATETIME NULL,
    CONSTRAINT fk_finance_snapshot_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_finance_snapshot_member FOREIGN KEY (generated_by_member_id) REFERENCES household_members(id) ON DELETE RESTRICT,
    UNIQUE KEY uq_finance_snapshot_run (household_id, run_key),
    INDEX idx_finance_snapshot_month (household_id, month_start, status),
    INDEX idx_finance_snapshot_status (household_id, status, started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_recommendations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    household_id BIGINT UNSIGNED NOT NULL,
    snapshot_id BIGINT UNSIGNED NOT NULL,
    inventory_item_id BIGINT UNSIGNED NULL,
    recommendation_type ENUM('budget_alert','price_increase','compare_supplier','use_first','reduce_waste','bulk_buy','review_data') NOT NULL,
    generation_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    title VARCHAR(180) NOT NULL,
    rationale TEXT NOT NULL,
    recommended_action TEXT NOT NULL,
    estimated_impact DECIMAL(12,2) NULL,
    priority ENUM('low','medium','high','critical') NOT NULL DEFAULT 'medium',
    due_on DATE NULL,
    status ENUM('pending','accepted','dismissed','completed') NOT NULL DEFAULT 'pending',
    related_task_id BIGINT UNSIGNED NULL,
    acted_by_member_id BIGINT UNSIGNED NULL,
    acted_at DATETIME NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_finance_recommendation_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_finance_recommendation_snapshot FOREIGN KEY (snapshot_id) REFERENCES household_finance_snapshots(id) ON DELETE CASCADE,
    CONSTRAINT fk_finance_recommendation_item FOREIGN KEY (inventory_item_id) REFERENCES inventory_items(id) ON DELETE SET NULL,
    CONSTRAINT fk_finance_recommendation_task FOREIGN KEY (related_task_id) REFERENCES household_tasks(id) ON DELETE SET NULL,
    CONSTRAINT fk_finance_recommendation_actor FOREIGN KEY (acted_by_member_id) REFERENCES household_members(id) ON DELETE SET NULL,
    UNIQUE KEY uq_finance_recommendation_generation (household_id, generation_key),
    INDEX idx_finance_recommendation_status (household_id, status, priority, due_on)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS finance_lifecycle_events (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    household_id BIGINT UNSIGNED NOT NULL,
    snapshot_id BIGINT UNSIGNED NULL,
    purchase_id BIGINT UNSIGNED NULL,
    waste_event_id BIGINT UNSIGNED NULL,
    recommendation_id BIGINT UNSIGNED NULL,
    member_id BIGINT UNSIGNED NULL,
    event_type VARCHAR(60) NOT NULL,
    from_status VARCHAR(30) NULL,
    to_status VARCHAR(30) NULL,
    notes TEXT NULL,
    occurred_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_finance_event_household FOREIGN KEY (household_id) REFERENCES households(id) ON DELETE CASCADE,
    CONSTRAINT fk_finance_event_snapshot FOREIGN KEY (snapshot_id) REFERENCES household_finance_snapshots(id) ON DELETE SET NULL,
    CONSTRAINT fk_finance_event_purchase FOREIGN KEY (purchase_id) REFERENCES food_purchase_records(id) ON DELETE SET NULL,
    CONSTRAINT fk_finance_event_waste FOREIGN KEY (waste_event_id) REFERENCES food_waste_events(id) ON DELETE SET NULL,
    CONSTRAINT fk_finance_event_recommendation FOREIGN KEY (recommendation_id) REFERENCES finance_recommendations(id) ON DELETE SET NULL,
    CONSTRAINT fk_finance_event_member FOREIGN KEY (member_id) REFERENCES household_members(id) ON DELETE SET NULL,
    INDEX idx_finance_events_household_time (household_id, occurred_at, id),
    INDEX idx_finance_events_recommendation (recommendation_id, occurred_at, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
